#!/bin/bash
# ==============================================================================
# Применение базовых системных настроек РЕД ОС
# ==============================================================================

# 1. Служба печати (CUPS)
systemctl enable cups --now || exit 1

# 2. Кэш шрифтов
fc-cache -fv || exit 1

# 3. Время Dual-Boot
timedatectl set-local-rtc 1 --adjust-system-clock || exit 1

exit 0
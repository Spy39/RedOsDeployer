#!/bin/bash
# ==============================================================================
# Скрипт онлайн-обновления РЕД ОС
# ==============================================================================

echo "--- Проверка подключения к интернету ---"
if ! ping -c 1 8.8.8.8 >/dev/null 2>&1; then
    echo "[!] ОШИБКА: Нет подключения к интернету."
    exit 1
fi

echo "--- Остановка фоновых служб (снятие блокировки DNF) ---"
# Убиваем системный автообновлятор, чтобы он не мешал нам работать
systemctl stop packagekit >/dev/null 2>&1 || true
killall -9 dnf >/dev/null 2>&1 || true
rm -f /var/lib/rpm/.rpm.lock >/dev/null 2>&1

echo "[i] Запуск обновления пакетов..."
# Обновляем все пакеты системы. 
# --skip-broken: пропускает конфликтующие пакеты (как redos-education)
# --allowerasing: разрешает удалять старые пакеты, если они мешают новым
dnf update -y --skip-broken --allowerasing

echo "--- Очистка системы после обновления ---"
dnf clean all >/dev/null 2>&1

echo "✅ Онлайн-обновление системы успешно завершено!"
exit 0